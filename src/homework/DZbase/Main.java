// Создание многомерного массива
import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        /*
         * Что делаем:
         * 1) Создаём двумерный массив int размером 3 строки × 4 столбца.
         * 2) Заполняем его числами, которые введёт пользователь.
         * 3) Находим максимальный элемент и его "координаты": (row, col).
         * 4) Выводим матрицу красиво.
         * 5) В качестве тренировки посчитаем сумму по каждой строке и по каждому столбцу.
         *
         * Важное про индексы:
         * - i -- индекс строки (идёт сверху вниз).
         * - j -- индекс столбца (идёт слева направо).
         * - Индексация с нуля: первая строка -- i = 0, первый столбец -- j = 0.
         */

        int rows = 3;
        int cols = 4;
        // Создаём "дом" из 3 строк, в каждой по 4 "квартирки".
        // По умолчанию везде лежит 0, потому что int -- примитивный тип.
        int[][] a = new int[rows][cols];

        // Визуализация (сразу после создания):
        //   Строка 0: [0, 0, 0, 0]
        //   Строка 1: [0, 0, 0, 0]
        //   Строка 2: [0, 0, 0, 0]

        Scanner sc = new Scanner(System.in);
        System.out.println("Введите " + (rows * cols) + " целых чисел (матрица 3×4):");

        // Два вложенных цикла: внешний -- бежит по строкам (i),
        // внутренний -- по столбцам внутри текущей строки (j).
        for (int i = 0; i < a.length; i++) {          // a.length -- количество строк
            for (int j = 0; j < a[i].length; j++) {   // a[i].length -- число столбцов в i-й строке
                a[i][j] = sc.nextInt();               // кладём введённое число в ячейку (i, j)
            }
        }
    
        // Инициализируем максимум первым элементом матрицы.
        // Так корректно работает, даже если все числа отрицательные.
        int max = a[0][0];
        int maxRow = 0;  // здесь запомним индекс строки максимума
        int maxCol = 0;  // здесь -- индекс столбца максимума

        // Проходим по всем элементам и обновляем максимум при необходимости.
        for (int i = 0; i < a.length; i++) {
            for (int j = 0; j < a[i].length; j++) {
                if (a[i][j] > max) {
                    max = a[i][j];
                    maxRow = i;
                    maxCol = j;
                }
            }
        }

        // Печатаем результат: координаты по нулям (0..rows-1, 0..cols-1).
        System.out.println("Максимум: " + max +
                ", позиция: (строка " + maxRow + ", столбец " + maxCol + ")");

        // Красиво выведем всю матрицу в виде прямоугольной таблицы.
        // %4d -- форматированный вывод: ширина 4 символа, чтобы столбцы не "прыгали".
        System.out.println("\nМатрица:");
        for (int i = 0; i < a.length; i++) {
            for (int j = 0; j < a[i].length; j++) {
                System.out.printf("%4d", a[i][j]);
            }
            System.out.println(); // перевод строки после каждой строки матрицы
        }

        // Дополнительно: сумма по каждой строке
        System.out.println("\nСумма по строкам:");
        for (int i = 0; i < a.length; i++) {
            int sumRow = 0;
            for (int j = 0; j < a[i].length; j++) {
                sumRow += a[i][j];
            }
            System.out.println("Строка " + i + ": " + sumRow);
        }

        // Дополнительно: сумма по каждому столбцу
        System.out.println("\nСумма по столбцам:");
        for (int j = 0; j < cols; j++) {   // cols == a[0].length для прямоугольной матрицы
            int sumCol = 0;
            for (int i = 0; i < rows; i++) {
                sumCol += a[i][j];
            }
            System.out.println("Столбец " + j + ": " + sumCol);
        }
        // Частые ошибки (на заметку):
        // 1) Путают размеры: a.length -- это число СТРОК, а a[i].length -- число СТОЛБЦОВ в i-й строке.
        // 2) Пишут <= вместо < в условиях цикла и вылетают за границы массива.
        // 3) Путают порядок индексов: сначала строка (i), потом столбец (j): a[i][j], не наоборот.
        // 4) Пытаются изменить размер уже созданного массива -- нельзя, создавайте новый.
        // 5) В Java есть "зубчатые" (неровные) 2D-массивы: new int[3][];
        //    тогда длина строк может различаться, и a[i].length надо брать для КАЖДОЙ строки.
    }
}
